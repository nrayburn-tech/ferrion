import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.function.IntPredicate;

/**
 * Prints the Rust source of {@code crates/ferrion_lexer/src/unicode_tables.rs}: the code points for
 * which this JDK's {@code Character.isJavaIdentifierStart}, {@code isJavaIdentifierPart}, and
 * {@code isIdentifierIgnorable} return true, as sorted, inclusive ranges.
 *
 * <p>Run it with the newest GA JDK: {@code java tools/unicode-tables/UnicodeTables.java}.
 */
public final class UnicodeTables {
  private UnicodeTables() {}

  private static final int RANGES_PER_LINE = 4;

  public static void main(String[] args) throws IOException {
    for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
      if (Character.isJavaIdentifierStart(cp) && !Character.isJavaIdentifierPart(cp)) {
        throw new IllegalStateException("start but not part: " + Integer.toHexString(cp));
      }
      if (Character.isIdentifierIgnorable(cp) && !Character.isJavaIdentifierPart(cp)) {
        throw new IllegalStateException("ignorable but not part: " + Integer.toHexString(cp));
      }
    }

    StringBuilder out = new StringBuilder();
    out.append("//! Java identifier character tables (JLS §3.8), generated by\n");
    out.append("//! `tools/unicode-tables/UnicodeTables.java`. Don't edit by hand.\n");
    out.append("//!\n");
    out.append("//! JDK: ").append(Runtime.version()).append('\n');
    out.append("//! Unicode: ").append(unicodeVersion()).append('\n');
    table(out, "JAVA_IDENTIFIER_START", "Character.isJavaIdentifierStart",
        Character::isJavaIdentifierStart);
    table(out, "JAVA_IDENTIFIER_PART", "Character.isJavaIdentifierPart",
        Character::isJavaIdentifierPart);
    table(out, "IDENTIFIER_IGNORABLE", "Character.isIdentifierIgnorable",
        Character::isIdentifierIgnorable);
    System.out.print(out);
  }

  private static void table(StringBuilder out, String name, String method, IntPredicate test) {
    List<int[]> ranges = new ArrayList<>();
    int start = -1;
    for (int cp = 0; cp <= Character.MAX_CODE_POINT + 1; cp++) {
      boolean in = cp <= Character.MAX_CODE_POINT && test.test(cp);
      if (in && start < 0) {
        start = cp;
      } else if (!in && start >= 0) {
        ranges.add(new int[] {start, cp - 1});
        start = -1;
      }
    }
    out.append('\n');
    out.append("/// Inclusive ranges of the code points for which `").append(method)
        .append("` is true.\n");
    out.append("#[rustfmt::skip]\n");
    out.append("pub(crate) static ").append(name).append(": &[(u32, u32)] = &[\n");
    for (int i = 0; i < ranges.size(); i += RANGES_PER_LINE) {
      out.append("   ");
      for (int j = i; j < Math.min(i + RANGES_PER_LINE, ranges.size()); j++) {
        out.append(String.format(" (0x%05X, 0x%05X),", ranges.get(j)[0], ranges.get(j)[1]));
      }
      out.append('\n');
    }
    out.append("];\n");
  }

  /** The Unicode version, from the notice the JDK ships for the Unicode Character Database. */
  private static String unicodeVersion() throws IOException {
    Path notice = Path.of(System.getProperty("java.home"), "legal", "java.base", "unicode.md");
    if (Files.exists(notice)) {
      for (String line : Files.readAllLines(notice, StandardCharsets.UTF_8)) {
        int at = line.indexOf("Version ");
        if (line.startsWith("##") && at >= 0) {
          return line.substring(at + "Version ".length()).strip();
        }
      }
    }
    return "unknown";
  }
}
