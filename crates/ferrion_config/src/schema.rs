//! The JSON Schema of `ferrion.jsonc`, generated from the key tables the validator uses.
//!
//! The schema can't express everything the validator checks (a glob's syntax, duplicate keys,
//! the nesting limit), so the validator stays the authority. `rules` accepts any rule name until
//! C1 generates the list of rules into it.

use crate::jsonc::write_json_string;
use crate::keys::{ENTRY_KEYS, Key, LEVELS, ROOT_KEYS, RULE_SETTING_KEYS, Shape};

/// Where the schema is committed, relative to the workspace root.
pub const SCHEMA_PATH: &str = "schemas/ferrion.schema.json";

/// The schema, as pretty-printed JSON ending with a line break.
pub fn json_schema() -> String {
    let mut root = vec![
        (
            "$schema",
            str("https://json-schema.org/draft/2020-12/schema"),
        ),
        ("title", str("ferrion.jsonc")),
        (
            "description",
            str(
                "The configuration of Ferrion, the Java formatter and linter. Generated by `cargo codegen` (tools/codegen) from crates/ferrion_config/src/keys.rs.",
            ),
        ),
    ];
    root.extend(object_schema(ROOT_KEYS));
    root.push((
        "$defs",
        Json::Object(vec![
            (
                "entry",
                Json::Object(
                    [("description", str("A config entry."))]
                        .into_iter()
                        .chain(object_schema(ENTRY_KEYS))
                        .collect(),
                ),
            ),
            (
                "glob",
                Json::Object(vec![
                    ("type", str("string")),
                    ("minLength", Json::Number(1)),
                    (
                        "description",
                        str("A glob, relative to the working directory, with `/` between folders. `*` doesn't match `/`, and `**` as a whole segment matches any number of folders."),
                    ),
                ]),
            ),
            (
                "level",
                Json::Object(vec![("enum", Json::Array(LEVELS.iter().map(|l| str(l)).collect()))]),
            ),
            (
                "ruleSetting",
                Json::Object(vec![(
                    "oneOf",
                    Json::Array(vec![
                        reference("level"),
                        Json::Object(object_schema(RULE_SETTING_KEYS)),
                    ]),
                )]),
            ),
        ]),
    ));
    let mut out = String::new();
    Json::Object(root).write(&mut out, 0);
    out.push('\n');
    out
}

/// The members of an object schema with exactly `keys`.
fn object_schema(keys: &[Key]) -> Vec<(&'static str, Json)> {
    let properties = keys
        .iter()
        .map(|key| {
            let mut schema = shape_schema(key.shape);
            if let Json::Object(members) = &mut schema {
                members.push(("description", str(key.description)));
            }
            (key.name, schema)
        })
        .collect();
    let mut members = vec![
        ("type", str("object")),
        ("properties", Json::Object(properties)),
        ("additionalProperties", Json::Bool(false)),
    ];
    let required: Vec<Json> = keys
        .iter()
        .filter(|k| k.required)
        .map(|k| str(k.name))
        .collect();
    if !required.is_empty() {
        members.push(("required", Json::Array(required)));
    }
    members
}

fn shape_schema(shape: Shape) -> Json {
    match shape {
        Shape::String => Json::Object(vec![("type", str("string"))]),
        Shape::Bool => Json::Object(vec![("type", str("boolean"))]),
        Shape::Level => reference("level"),
        Shape::Globs { non_empty } => {
            let mut members = vec![("type", str("array")), ("items", reference("glob"))];
            if non_empty {
                members.push(("minItems", Json::Number(1)));
            }
            Json::Object(members)
        }
        Shape::Names => Json::Object(vec![
            ("type", str("array")),
            ("items", Json::Object(vec![("type", str("string"))])),
        ]),
        Shape::Object(keys) => Json::Object(object_schema(keys)),
        Shape::Entries => Json::Object(vec![("type", str("array")), ("items", reference("entry"))]),
        Shape::Rules => Json::Object(vec![
            ("type", str("object")),
            ("additionalProperties", reference("ruleSetting")),
        ]),
        Shape::RuleSetting => reference("ruleSetting"),
        Shape::Options => Json::Object(vec![("type", str("object"))]),
    }
}

/// `{ "$ref": "#/$defs/<name>" }`, which keeps a description next to it.
fn reference(name: &str) -> Json {
    Json::Object(vec![("$ref", Json::String(format!("#/$defs/{name}")))])
}

fn str(s: &str) -> Json {
    Json::String(s.to_owned())
}

enum Json {
    Bool(bool),
    Number(i64),
    String(String),
    Array(Vec<Json>),
    Object(Vec<(&'static str, Json)>),
}

impl Json {
    /// Writes the value with two spaces per level, as `serde_json`'s pretty printer does; arrays
    /// of strings stay on one line.
    fn write(&self, out: &mut String, indent: usize) {
        match self {
            Json::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
            Json::Number(n) => out.push_str(&n.to_string()),
            Json::String(s) => write_json_string(out, s),
            Json::Array(items) if items.iter().all(|i| matches!(i, Json::String(_))) => {
                out.push('[');
                for (i, item) in items.iter().enumerate() {
                    if i > 0 {
                        out.push_str(", ");
                    }
                    item.write(out, indent);
                }
                out.push(']');
            }
            Json::Array(items) => {
                out.push('[');
                for (i, item) in items.iter().enumerate() {
                    out.push_str(if i > 0 { ",\n" } else { "\n" });
                    out.push_str(&"  ".repeat(indent + 1));
                    item.write(out, indent + 1);
                }
                out.push('\n');
                out.push_str(&"  ".repeat(indent));
                out.push(']');
            }
            Json::Object(members) => {
                out.push('{');
                for (i, (key, value)) in members.iter().enumerate() {
                    out.push_str(if i > 0 { ",\n" } else { "\n" });
                    out.push_str(&"  ".repeat(indent + 1));
                    write_json_string(out, key);
                    out.push_str(": ");
                    value.write(out, indent + 1);
                }
                out.push('\n');
                out.push_str(&"  ".repeat(indent));
                out.push('}');
            }
        }
    }
}
